// Usage: node tools/sync-engine.mjs (Node 22 with module.stripTypeScriptTypes).
// Reads the sibling apps repo; writes only this site's play.html.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';
import { Script } from 'node:vm';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, '..', 'beequation', 'packages', 'engine', 'src', 'index.ts');
const pagePath = path.join(root, 'play.html');
const start = '// ---- engine: generated by tools/sync-engine.mjs from packages/engine (do not edit) ----';
const end = '// ---- end engine ----';
const source = fs.readFileSync(sourcePath, 'utf8');
let engine;
try {
  engine = stripTypeScriptTypes(source, { mode: 'strip' });
} catch (error) {
  if (error.code !== 'ERR_UNSUPPORTED_TYPESCRIPT_SYNTAX') throw error;
  engine = stripTypeScriptTypes(source, { mode: 'transform' });
}
engine = engine.replace(/^export\s+(?=(?:const|let|var|function|class)\b)/gm, '')
  .replace(/[ \t]+$/gm, '').trimEnd();
// Reject any remaining module syntax or invalid JavaScript before writing.
new Script(engine, { filename: 'beequation-engine.js' });

const page = fs.readFileSync(pagePath, 'utf8');
let from, to;
if (page.includes(start) || page.includes(end)) {
  if (page.split(start).length !== 2 || page.split(end).length !== 2) {
    throw new Error('play.html must contain exactly one engine marker pair');
  }
  from = page.indexOf(start);
  to = page.indexOf(end) + end.length;
  if (page.indexOf(end) < from) throw new Error('Engine markers are out of order');
} else {
  const legacyStart = '// Beequation puzzle engine.';
  const legacyEnd = '// ---------- helpers ----------';
  if (page.split(legacyStart).length !== 2 || page.split(legacyEnd).length !== 2) {
    throw new Error('Cannot locate the original engine block in play.html');
  }
  from = page.indexOf(legacyStart);
  to = page.indexOf(legacyEnd);
  if (to < from) throw new Error('Original engine boundaries are out of order');
}
const generated = `${start}\n${engine}\n${end}`;
const next = page.slice(0, from) + generated + (page.includes(start) ? '' : '\n\n') + page.slice(to);
if (next !== page) fs.writeFileSync(pagePath, next);
console.log(next === page ? 'play.html engine is already up to date' : 'Synced play.html engine from packages/engine');
